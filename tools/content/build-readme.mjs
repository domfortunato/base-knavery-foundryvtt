/**
 * The welcome window is also the README and the Foundry package listing (user, 2026-11-14).
 * This writes both from the welcome's own words (lang/en.json KNAVERY.Welcome, the disclaimer
 * and the logo credit) and data (module/welcome-data.js), so a change is made once:
 *
 *   - README.md: the two blocks between `<!-- welcome:start -->`/`<!-- welcome:end -->` and
 *     `<!-- licensing:start -->`/`<!-- licensing:end -->`. Everything else in it is hand-written.
 *   - docs/foundry-listing.html: an HTML fragment to paste into the package form on
 *     foundryvtt.com. Plain tags only, absolute links, images from the public GitHub mirror's
 *     `master` (the released state), white versions because the Foundry site is dark.
 *     No GitHub Pages (user, 2026-11-14).
 *
 *   npm run build:readme            write both
 *   npm run build:readme -- --check fail if either is out of date (part of `npm run check`)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import { ART_CREDITS, BOOKS, CC_BY_URL, WELCOME_BOOKENDS } from "../../module/welcome-data.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const read = (p) => readFileSync(resolve(ROOT, p), "utf8");
const lang = JSON.parse(read("lang/en.json"));
const manifest = JSON.parse(read("system.json"));
const check = process.argv.includes("--check");

/** A KNAVERY.* key from the language file, with {name} filled. */
const L = (key, data = {}) => {
  const v = key.replace(/^KNAVERY\./, "").split(".").reduce((o, k) => o?.[k], lang.KNAVERY);
  if (typeof v !== "string") throw new Error(`build-readme: no string ${key}`);
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in data ? data[k] : m));
};
const W = (k, data) => L(`KNAVERY.Welcome.${k}`, data);
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const author = manifest.authors?.[0] ?? { name: "Dom Bosco" };
const repo = manifest.url.replace(/\/$/, "");
const raw = `${repo.replace("https://github.com/", "https://raw.githubusercontent.com/")}/master/`;
const portrait = (n, white) => `art/welcome/portraits/${n}${white ? "-white" : ""}.png`;
const alt = esc(W("PortraitAlt"));
const knave1eBody = (href) => W("Knave1eBody", { license: `<a href="${href}">${esc(W("Knave1eLicense"))}</a>` });
// The README keeps the credit only; its list of changes stays in the welcome window, the listing and
// LICENSE.txt (user, 2026-11-14: keep the README tight).
const knave1eCredit = (href) => knave1eBody(href).replace(/\s*Changes:.*$/s, "");
const credit = (a, link) => `${link(a.url, esc(a.name))}, ${esc(a.by)}: ${a.licenseUrl ? link(a.licenseUrl, esc(a.license)) : esc(a.license)}`;
const AI = [["🖌️", "NoAiArt", "NoAiArtBody"], ["📜", "NoAiText", "NoAiTextBody"], ["🧠", "AiCode", null]];

// ---- README.md ------------------------------------------------------------------------------
const mdLink = (href, text) => `[${text}](${href})`;
const picture = (n) => `<picture><source media="(prefers-color-scheme: dark)" srcset="${portrait(n, true)}">`
  + `<img src="${portrait(n)}" alt="${alt}" height="100" align="middle"></picture>`;
const NOTE = "generated by `npm run build:readme` from lang/en.json and module/welcome-data.js: edit those, not this";

const readmeWelcome = [
  `<!-- welcome:start (${NOTE}) -->`,
  `<h1 align="center">${picture(WELCOME_BOOKENDS.left)} ${esc(manifest.title)}™ ${picture(WELCOME_BOOKENDS.right)}</h1>`,
  `<p align="center">by <a href="${author.url}">${esc(author.name)}</a></p>`,
  "",
  `<p align="center"><em>${esc(W("Unofficial"))}<br>${esc(W("NotEndorsed"))}</em></p>`,
  "",
  `## ${W("RulesHeading")}`,
  "",
  ...["1e", "2e", "Mix"].map((k) => `- **${W(`Rules${k}Title`)}** ${W(`Rules${k}Body`)}`),
  "",
  `## ${W("GetTheBook")}`,
  "",
  W("Author"),
  "",
  ...BOOKS.map((b) => `- **${L(b.label)}**: ${b.links.map((l) => mdLink(l.href, L(l.label))).join(" · ")}`
    + (b.note ? `. ${L(b.note)}` : "")),
  "",
  `## ${W("AiHeading")}`,
  "",
  ...AI.map(([icon, head, body]) => `- ${icon} **${W(head)}**${body ? ` ${W(body)}` : ""}`),
  "",
  "<!-- welcome:end -->",
].join("\n");

const fold = (summary, body) => `<details><summary><b>${summary}</b></summary>\n\n${body}\n\n</details>`;
const readmeLicensing = [
  `<!-- licensing:start (${NOTE}) -->`,
  `## ${W("Licensing")}`,
  "",
  L("KNAVERY.Disclaimer"),
  "",
  `### ${W("KnaveLicensing")}`,
  "",
  fold(esc(W("Knave1eHeading")), knave1eCredit(CC_BY_URL)),
  fold(esc(W("Knave2eHeading")), L("KNAVERY.LogoCredit")),
  "",
  fold(esc(W("ArtLicensing")), ART_CREDITS.map((a) => `- ${credit(a, mdLink)}`).join("\n")),
  "",
  "For more detail see [LICENSE.txt](LICENSE.txt).",
  "",
  `<p align="right"><img src="logo/made-for-knave-yellow.png" alt="${esc(L("KNAVERY.MadeForKnave"))}" width="180"></p>`,
  "",
  "<!-- licensing:end -->",
].join("\n");

// ---- docs/foundry-listing.html --------------------------------------------------------------
const a = (href, text) => `<a href="${href}">${text}</a>`;
const img = (n) => `<img src="${raw}${portrait(n, true)}" alt="${alt}" width="100" height="100" style="vertical-align: middle;">`;
const listing = [
  `<!-- ${NOTE}. Paste into the package description on foundryvtt.com. -->`,
  `<h2 style="text-align: center;">${img(WELCOME_BOOKENDS.left)} ${esc(manifest.title)}™ ${img(WELCOME_BOOKENDS.right)}</h2>`,
  `<p style="text-align: center;">by ${a(author.url, esc(author.name))}</p>`,
  `<p style="text-align: center;"><em>${esc(W("Unofficial"))}<br>${esc(W("NotEndorsed"))}</em></p>`,
  `<h3>${esc(W("RulesHeading"))}</h3>`,
  "<ul>",
  ...["1e", "2e", "Mix"].map((k) => `  <li><strong>${esc(W(`Rules${k}Title`))}</strong> ${esc(W(`Rules${k}Body`))}</li>`),
  "</ul>",
  `<h3>${esc(W("GetTheBook"))}</h3>`,
  `<p>${esc(W("Author"))}</p>`,
  "<ul>",
  ...BOOKS.map((b) => `  <li><strong>${esc(L(b.label))}</strong>: ${b.links.map((l) => a(l.href, esc(L(l.label)))).join(" · ")}`
    + `${b.note ? `. ${esc(L(b.note))}` : ""}</li>`),
  "</ul>",
  `<h3>${esc(W("AiHeading"))}</h3>`,
  "<ul>",
  ...AI.map(([icon, head, body]) => `  <li>${icon} <strong>${esc(W(head))}</strong>${body ? ` ${esc(W(body))}` : ""}</li>`),
  "</ul>",
  `<h3>${esc(W("Licensing"))}</h3>`,
  `<p>${esc(L("KNAVERY.Disclaimer"))}</p>`,
  `<h4>${esc(W("Knave1eHeading"))}</h4>`,
  `<p>${knave1eBody(CC_BY_URL)}</p>`,
  `<h4>${esc(W("Knave2eHeading"))}</h4>`,
  `<p>${esc(L("KNAVERY.LogoCredit"))}</p>`,
  `<h4>${esc(W("ArtLicensing"))}</h4>`,
  "<ul>",
  ...ART_CREDITS.map((c) => `  <li>${credit(c, a)}</li>`),
  "</ul>",
  `<p>${a(repo, "Source, issues and the full licence on GitHub")}</p>`,
  `<p style="text-align: right;"><img src="${raw}logo/made-for-knave-white.png" alt="${esc(L("KNAVERY.MadeForKnave"))}" width="160"></p>`,
  "",
].join("\n");

// ---- write or check -------------------------------------------------------------------------
const between = (text, name, block) => {
  const re = new RegExp(`<!-- ${name}:start[^]*?<!-- ${name}:end -->`);
  if (!re.test(text)) throw new Error(`build-readme: README.md has no ${name}:start/end markers`);
  return text.replace(re, () => block);
};
// Line endings are compared away and kept as each file has them (git checks these out CRLF on Windows).
const lf = (t) => t.replace(/\r\n/g, "\n");
const asFile = (t, like) => (like.includes("\r\n") ? t.replace(/\n/g, "\r\n") : t);
const readme = lf(read("README.md"));
const nextReadme = between(between(readme, "welcome", readmeWelcome), "licensing", readmeLicensing);
const listingPath = resolve(ROOT, "docs/foundry-listing.html");
let listingFile = "";
try { listingFile = readFileSync(listingPath, "utf8"); } catch { /* first build */ }

const stale = [nextReadme !== readme && "README.md", listing !== lf(listingFile) && "docs/foundry-listing.html"].filter(Boolean);
if (check) {
  if (stale.length) {
    console.error(`readme: out of date with the welcome window: ${stale.join(", ")}. Run npm run build:readme.`);
    process.exit(1);
  }
  console.log("readme: README.md and docs/foundry-listing.html match the welcome window.");
} else {
  writeFileSync(resolve(ROOT, "README.md"), asFile(nextReadme, read("README.md")));
  mkdirSync(dirname(listingPath), { recursive: true });
  writeFileSync(listingPath, asFile(listing, listingFile));
  console.log(stale.length ? `readme: wrote ${stale.join(", ")}` : "readme: already up to date");
}
